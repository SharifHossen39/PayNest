CREATE TABLE paynest.transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_wallet_id BIGINT CONSTRAINT nn_transactions_sender_wallet NOT NULL,
    receiver_wallet_id BIGINT CONSTRAINT nn_transactions_receiver_wallet NOT NULL,
    amount NUMERIC(19, 2) CONSTRAINT nn_transactions_amount NOT NULL,
    status VARCHAR(20) CONSTRAINT nn_transactions_status NOT NULL,
    created_at TIMESTAMPTZ CONSTRAINT nn_transactions_created_at NOT NULL,
    CONSTRAINT fk_transactions_sender_wallet
        FOREIGN KEY (sender_wallet_id) REFERENCES paynest.wallets (id),
    CONSTRAINT fk_transactions_receiver_wallet
        FOREIGN KEY (receiver_wallet_id) REFERENCES paynest.wallets (id),
    CONSTRAINT ck_transactions_positive_amount
        CHECK (amount > 0.00 AND amount <> 'NaN'::NUMERIC),
    CONSTRAINT ck_transactions_distinct_wallets
        CHECK (sender_wallet_id <> receiver_wallet_id),
    CONSTRAINT ck_transactions_completed_status
        CHECK (status = 'COMPLETED')
);

CREATE INDEX idx_transactions_sender_history
    ON paynest.transactions (sender_wallet_id, created_at DESC, id DESC);

CREATE INDEX idx_transactions_receiver_history
    ON paynest.transactions (receiver_wallet_id, created_at DESC, id DESC);
