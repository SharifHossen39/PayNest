CREATE TABLE paynest.wallets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    balance NUMERIC(19, 2) NOT NULL DEFAULT 0.00,
    currency CHAR(3) NOT NULL DEFAULT 'USD',
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_wallets_user FOREIGN KEY (user_id) REFERENCES paynest.users (id),
    CONSTRAINT uk_wallets_user UNIQUE (user_id),
    CONSTRAINT ck_wallets_usd_currency CHECK (currency = 'USD'),
    CONSTRAINT ck_wallets_non_negative_balance CHECK (balance >= 0.00 AND balance <> 'NaN'::NUMERIC)
);
